#!/usr/bin/env python3
"""Reconstruct the exact K4 kernel from modular residue files.

Standalone, standard-library, no imports from periodlab.
Run: python scripts/reconstruct_k4.py DIRECTORY
The residue files are generated by scripts/extract_k4_mod.cpp.
"""
import json
import math
import hashlib
import sys
from fractions import Fraction
from functools import reduce
from pathlib import Path

PRIMES = (1000000007,1000000009,1000000021,1000000033,
          1000000087,1000000093,1000000097,1000000103,
          1000000123,1000000181,1000000207,1000000223,
          1000000241,1000000271,1000000289)
M = 1692
K = 4

def rational_reconstruct(r, modulus):
    if r == 0:
        return Fraction(0)
    bound = math.isqrt(modulus//2)
    a0,a1 = modulus,r
    b0,b1 = 0,1
    while a1 > bound:
        q = a0//a1
        a0,a1 = a1,a0-q*a1
        b0,b1 = b1,b0-q*b1
    if not b1 or abs(b1)>bound or math.gcd(a1,b1)!=1:
        return None
    if (a1*pow(b1,-1,modulus))%modulus != r:
        return None
    return Fraction(a1,b1)

def primes_up_to(n):
    sieve=bytearray(b'\x01')*(n+1)
    sieve[:2]=b'\0\0'
    for p in range(2,math.isqrt(n)+1):
        if sieve[p]:
            sieve[p*p:n+1:p]=b'\0'*len(range(p*p,n+1,p))
    return [p for p in range(2,n+1) if sieve[p]]

def valuation(n,p):
    total=0
    while n:
        n//=p
        total+=n
    return total

def verify_relation(relation):
    if not relation or relation[-1][0]!=M:
        raise ValueError("missing terminal weight in relation")
    if sum(a*c for a,c in relation)!=0:
        raise ValueError("nonzero total weight difference")
    if sum(c for a,c in relation)==0:
        raise ValueError("expected dimension-changing witness")
    primes=primes_up_to((K+1)*M)
    first_mismatch=None
    mismatch_count=0
    for m in range(1,K+2):
        bad=[]
        for p in primes:
            if p>m*M:
                break
            delta=sum(c*valuation(m*a,p) for a,c in relation if m*a>=p)
            if delta:
                bad.append(p)
        print(f"supported coefficient m={m}: {len(bad)} mismatched prime valuations",flush=True)
        if m<=K and bad:
            raise ValueError(f"false coefficient identity at m={m}, prime {bad[0]}")
        if m==K+1:
            if not bad:
                raise ValueError("fifth coefficient unexpectedly agrees")
            first_mismatch=m
            mismatch_count=len(bad)
    return first_mismatch,mismatch_count

def reconstruct(root):
    coefficients=[0]*M
    modulus=1
    for index,p in enumerate(PRIMES,1):
        file=root/f"residue_{p}.txt"
        residues=[0]*M
        for line in file.read_text(encoding="utf-8").splitlines():
            a,v=map(int,line.split())
            if not 1<=a<=M:
                raise ValueError("weight index out of range")
            residues[a-1]=v%p
        inverse=pow(modulus,-1,p)
        coefficients=[x+modulus*((y-x)*inverse%p)
                      for x,y in zip(coefficients,residues)]
        modulus*=p
        fractions=[rational_reconstruct(x,modulus) for x in coefficients]
        if any(v is None for v in fractions):
            continue
        denominator=math.lcm(*(v.denominator for v in fractions))
        signed=[int(v*denominator) for v in fractions]
        common=reduce(math.gcd,(abs(v) for v in signed if v))
        signed=[v//common for v in signed]
        relation=[[a,v] for a,v in enumerate(signed,1) if v]
        try:
            first_mismatch,mismatch_count=verify_relation(relation)
        except ValueError:
            continue
        left=sum(max(v,0) for _,v in relation)
        right=sum(max(-v,0) for _,v in relation)
        H=sum(a*max(v,0) for a,v in relation)
        padding=2*M
        result={"schema":"periodlab/k4-exact-relation/v1","K":K,
                "max_weight":M,"relation":relation,"old_total_weight":H,
                "weight_counts":[left,right],"common_unit_padding":padding,
                "terminal_total_weight":H+padding,
                "terminal_dimensions":[left+padding-1,right+padding-1],
                "verified_equal_m":[1,2,3,4],
                "verified_different_m":first_mismatch,
                "fifth_mismatch_prime_count":mismatch_count,
                "modular_primes_used":index}
        data=json.dumps(result,sort_keys=True,indent=2)+"\n"
        outfile=root/"k4_exact_relation.json"
        outfile.write_text(data,encoding="utf-8")
        print("VERIFIED",len(relation),"signed entries",
              "SHA256",hashlib.sha256(data.encode()).hexdigest(),flush=True)
        return result
    raise ValueError("insufficient modular information to reconstruct and verify exact kernel")

if __name__=="__main__":
    if len(sys.argv)!=2:
        raise SystemExit("Usage: python scripts/reconstruct_k4.py DIRECTORY")
    reconstruct(Path(sys.argv[1]))
